"""App store: videos (doubles as the job queue), swings, cards, references.

Two backends behind one interface:
  * PostgreSQL (`postgresql://...`): the app's source of truth; logical replication
    feeds Debezium CDC -> Kafka -> Iceberg (pipeline/stream.py).
  * SQLite (a file path): tests and offline use.
SQL is written once with `?` placeholders and portable upserts (ON CONFLICT ... DO
UPDATE, RETURNING); the connection wrapper translates placeholders for Postgres.
"""

import json
import os
import sqlite3
from contextlib import contextmanager
from pathlib import Path

_NOW_SQLITE = "(datetime('now', 'localtime'))"
_NOW_PG = "(to_char(now(), 'YYYY-MM-DD HH24:MI:SS'))"


def _schema(pg: bool) -> list[str]:
    now = _NOW_PG if pg else _NOW_SQLITE
    pk = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if pg else "INTEGER PRIMARY KEY AUTOINCREMENT"
    real = "DOUBLE PRECISION" if pg else "REAL"
    ref = "BIGINT" if pg else "INTEGER"
    return [
        f"""CREATE TABLE IF NOT EXISTS videos (
            id {pk},
            content_hash TEXT UNIQUE NOT NULL,
            path TEXT NOT NULL,
            source TEXT NOT NULL,                 -- golfzon | upload
            nasmo_seq {ref},
            session_key TEXT NOT NULL,            -- round / upload batch
            session_label TEXT,
            seq_no INTEGER NOT NULL,              -- order inside the session
            shot_at TEXT,                         -- when the shot happened (golfzon) or upload time
            uploaded_at TEXT NOT NULL DEFAULT {now},
            status TEXT NOT NULL DEFAULT 'queued', -- queued | processing | done | failed
            attempts INTEGER NOT NULL DEFAULT 0,
            error TEXT,
            club TEXT, club_group TEXT, club_source TEXT, club_conf {real},
            ball_flight_code INTEGER, carry_m {real}, hole INTEGER,
            width INTEGER, fps {real})""",
        f"""CREATE TABLE IF NOT EXISTS swings (
            video_id {ref} PRIMARY KEY REFERENCES videos(id),
            feature_version TEXT, p1 INTEGER, p4 INTEGER, p7 INTEGER, p10 INTEGER,
            metrics_json TEXT NOT NULL)""",
        f"""CREATE TABLE IF NOT EXISTS cards (
            video_id {ref} PRIMARY KEY REFERENCES videos(id),
            good TEXT, fix TEXT, cue TEXT, extra_json TEXT, fix_key TEXT, good_key TEXT,
            confidence TEXT, image_path TEXT, evidence_json TEXT,
            created_at TEXT NOT NULL DEFAULT {now})""",
        f"""CREATE TABLE IF NOT EXISTS reference (
            club_group TEXT PRIMARY KEY,
            video_id {ref} NOT NULL REFERENCES videos(id),
            set_at TEXT NOT NULL DEFAULT {now})""",
        "CREATE INDEX IF NOT EXISTS idx_videos_status ON videos(status)",
    ]


class Row(dict):
    """dict row that also supports positional access (r[0], r[:]) like sqlite3.Row."""

    def __getitem__(self, key):
        if isinstance(key, (int, slice)):
            return tuple(self.values())[key]
        return super().__getitem__(key)


class _Result:
    def __init__(self, cur):
        self.cur = cur
        self.lastrowid = getattr(cur, "lastrowid", None)

    def _row(self, r):
        if r is None:
            return None
        if isinstance(r, sqlite3.Row):
            return Row(zip(r.keys(), tuple(r)))
        return Row(r)

    def fetchone(self):
        return self._row(self.cur.fetchone())

    def fetchall(self):
        return [self._row(r) for r in self.cur.fetchall()]

    def __iter__(self):
        return iter(self.fetchall())


class _Conn:
    def __init__(self, raw, pg: bool):
        self.raw, self.pg = raw, pg

    def execute(self, sql: str, params=()) -> _Result:
        if self.pg:
            cur = self.raw.cursor()
            cur.execute(sql.replace("?", "%s"), tuple(params))
            return _Result(cur)
        return _Result(self.raw.execute(sql, tuple(params)))


class Store:
    def __init__(self, target):
        self.target = str(target)
        self.pg = self.target.startswith("postgresql://")
        if not self.pg:
            Path(self.target).parent.mkdir(parents=True, exist_ok=True)
        with self.conn() as c:
            for stmt in _schema(self.pg):
                c.execute(stmt)

    @contextmanager
    def conn(self):
        if self.pg:
            import psycopg
            from psycopg.rows import dict_row

            # Without a timeout, connecting while WSL's port relay is up but Postgres is not
            # yet hangs forever (seen at Windows logon), so fail fast and let the caller retry.
            raw = psycopg.connect(self.target, row_factory=dict_row, connect_timeout=10)
        else:
            raw = sqlite3.connect(self.target, timeout=30)
            raw.row_factory = sqlite3.Row
        try:
            yield _Conn(raw, self.pg)
            raw.commit()
        except Exception:
            raw.rollback()
            raise
        finally:
            raw.close()

    # --- videos / queue -------------------------------------------------
    def add_video(self, **v) -> tuple[int, bool]:
        """Insert unless the content hash exists. Returns (video_id, created)."""
        with self.conn() as c:
            row = c.execute("SELECT id FROM videos WHERE content_hash = ?", (v["content_hash"],)).fetchone()
            if row:
                return row["id"], False
            if "seq_no" not in v:
                v["seq_no"] = c.execute("SELECT COALESCE(MAX(seq_no), 0) + 1 FROM videos WHERE session_key = ?",
                                        (v["session_key"],)).fetchone()[0]
            cols = ", ".join(v)
            new = c.execute(f"INSERT INTO videos ({cols}) VALUES ({', '.join('?' * len(v))}) RETURNING id",
                            tuple(v.values())).fetchone()
            return new["id"], True

    def claim_next(self) -> Row | None:
        """Oldest queued video, marked processing. Postgres: SKIP LOCKED so parallel workers never share a job."""
        lock = " FOR UPDATE SKIP LOCKED" if self.pg else ""
        with self.conn() as c:
            row = c.execute(f"SELECT * FROM videos WHERE status = 'queued' ORDER BY id LIMIT 1{lock}").fetchone()
            if row:
                c.execute("UPDATE videos SET status = 'processing', attempts = attempts + 1 WHERE id = ?", (row["id"],))
            return row

    def finish(self, video_id: int, status: str, error: str | None = None) -> None:
        with self.conn() as c:
            c.execute("UPDATE videos SET status = ?, error = ? WHERE id = ?", (status, error, video_id))

    def update_video(self, video_id: int, **fields) -> None:
        with self.conn() as c:
            sets = ", ".join(f"{k} = ?" for k in fields)
            c.execute(f"UPDATE videos SET {sets} WHERE id = ?", (*fields.values(), video_id))

    # --- results --------------------------------------------------------
    def _upsert(self, table: str, key: str, row: dict) -> None:
        cols = list(row)
        updates = ", ".join(f"{c} = excluded.{c}" for c in cols if c != key)
        with self.conn() as c:
            c.execute(f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join('?' * len(cols))}) "
                      f"ON CONFLICT ({key}) DO UPDATE SET {updates}", tuple(row.values()))

    def save_swing(self, video_id: int, phases: dict, metrics: dict) -> None:
        self._upsert("swings", "video_id", {
            "video_id": video_id, "feature_version": metrics.get("feature_version"),
            "p1": phases["P1"], "p4": phases["P4"], "p7": phases["P7"], "p10": phases["P10"],
            "metrics_json": json.dumps(metrics)})

    def save_card(self, video_id: int, card, image_path: str) -> None:
        self._upsert("cards", "video_id", {
            "video_id": video_id, "good": card.good, "fix": card.fix, "cue": card.cue,
            "extra_json": json.dumps(card.extra, ensure_ascii=False), "fix_key": card.fix_key,
            "good_key": card.good_key, "confidence": card.confidence, "image_path": image_path,
            "evidence_json": json.dumps(card.evidence, ensure_ascii=False)})

    def set_reference(self, club_group: str, video_id: int) -> None:
        self._upsert("reference", "club_group", {"club_group": club_group, "video_id": video_id})

    def references(self) -> dict[str, int]:
        with self.conn() as c:
            return {r["club_group"]: r["video_id"] for r in c.execute("SELECT * FROM reference")}


def default_store() -> "Store":
    """SWINGCOACH_DB (or APP_DATABASE_URL in platform/.env) if set, else the local SQLite file."""
    root = Path(__file__).resolve().parents[2]
    url = os.environ.get("SWINGCOACH_DB")
    env_file = root / "platform" / ".env"
    if not url and env_file.exists():
        env = dict(l.split("=", 1) for l in env_file.read_text(encoding="utf-8").splitlines() if "=" in l)
        url = env.get("APP_DATABASE_URL")
    return Store(url or root / "data" / "app.db")
